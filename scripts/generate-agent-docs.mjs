// ABOUTME: Generates public agent docs from the guide, MCP registrations and local OpenAPI schema.
// ABOUTME: --check rejects stale committed outputs without calling production or modifying game data.
import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const require = createRequire(new URL('../worker/package.json', import.meta.url));
const ts = require('typescript');
const { unstable_dev } = require('wrangler');
const check = process.argv.includes('--check');
const read = (file) => fs.readFile(path.join(root, file), 'utf8');
const guide = await read('docs/agent-guide.md');
const guideBody = guide.replace(/^---\n[\s\S]*?\n---\n/, '');
const source = ts.createSourceFile('agent.ts', await read('mcp/src/agent.ts'), ts.ScriptTarget.Latest, true);
const tools = [];
function literal(node) {
  if (!node || !(ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node))) {
    throw new Error('MCP tool names and descriptions must be static strings for documentation generation');
  }
  return node.text;
}
function visit(node) {
  if (ts.isCallExpression(node) && node.expression.getText(source) === 'this.server.tool') {
    tools.push({ name: literal(node.arguments[0]), description: literal(node.arguments[1]) });
  }
  ts.forEachChild(node, visit);
}
visit(source);
if (!tools.length || new Set(tools.map(t => t.name)).size !== tools.length) {
  throw new Error('Missing or duplicate MCP tool registrations');
}

// Start only local bindings. /openapi.json does not read D1, R2, or city state.
const worker = await unstable_dev(path.join(root, 'worker/src/index.ts'), {
  config: path.join(root, 'worker/wrangler.toml'),
  local: true, logLevel: 'error',
  experimental: { disableExperimentalWarning: true },
});
let schema;
try {
  const response = await worker.fetch('/openapi.json');
  if (!response.ok) throw new Error(`Local OpenAPI generation failed: ${response.status}`);
  schema = await response.json();
} finally {
  await worker.stop();
}
const methods = new Set(['get', 'post', 'put', 'patch', 'delete', 'head', 'options']);
const endpoints = Object.entries(schema.paths).flatMap(([route, operations]) =>
  Object.entries(operations).filter(([method]) => methods.has(method)).map(([method, operation]) => ({
    method: method.toUpperCase(), path: route,
    auth: operation.security?.some(s => s.Bearer) ? 'Required' : route === '/v1/cities' && method === 'get' ? 'Optional' : 'Public',
    description: operation.summary || operation.description || '',
  })),
).sort((a, b) => a.path.localeCompare(b.path, 'en') || a.method.localeCompare(b.method, 'en'));
if (!endpoints.some(e => e.path.endsWith('/batch'))) throw new Error('Incomplete local OpenAPI schema');
const cell = (value) => value.replaceAll('|', '\\|').replaceAll('\n', ' ');
const endpointTable = ['| Method | Path | Auth | Description |', '| --- | --- | --- | --- |',
  ...endpoints.map(e => `| ${e.method} | ${e.path} | ${e.auth} | ${cell(e.description)} |`)].join('\n');
const toolsMarkdown = '# MCP tool reference\n\nGenerated from MCP registrations. Use tools/list for live input schemas.\n\n' +
  tools.map(t => `## ${t.name}\n\n${t.description}`).join('\n\n') + '\n';
const apiMarkdown = '# Hallucinating Splines API reference\n\n' +
  'Base URL: https://api.hallucinatingsplines.com\n\n' +
  'Generated from the local OpenAPI schema and canonical agent guide. Full request/response schemas: https://api.hallucinatingsplines.com/openapi.json\n\n' +
  endpointTable + '\n\n## Documentation endpoints\n\n' +
  '- GET /v1/docs — this Markdown guide\n- GET /openapi.json — machine-readable schemas\n- GET /reference — interactive API explorer\n\n' +
  `## MCP tools (${tools.length})\n\n` + tools.map(t => `- ${t.name}: ${t.description.split('\n')[0]}`).join('\n') +
  '\n\n---\n\n' + guideBody;
const generated = '// ABOUTME: Generated from canonical docs; run npm run docs:generate to update.\n// ABOUTME: Do not edit this file directly; CI checks it against its sources.\n';
const outputs = new Map([
  ['site/src/generated/reference.json', JSON.stringify({ tools, endpoints }, null, 2) + '\n'],
  ['site/public/agent-guide.md', guideBody],
  ['site/public/skill.md', guide],
  ['site/public/mcp-tools.md', toolsMarkdown],
  ['site/public/api-reference.md', apiMarkdown],
  ['worker/src/generated/api-reference.ts', generated + `export const API_REFERENCE = ${JSON.stringify(apiMarkdown)};\n`],
  ['mcp/src/generated/agent-guide.ts', generated + `export const AGENT_GUIDE = ${JSON.stringify(guideBody)};\n`],
]);
let stale = false;
for (const [file, content] of outputs) {
  if (check) {
    if (await read(file).catch(() => null) !== content) {
      console.error(`Stale generated document: ${file}`);
      stale = true;
    }
  } else {
    await fs.mkdir(path.dirname(path.join(root, file)), { recursive: true });
    await fs.writeFile(path.join(root, file), content);
  }
}
if (stale) {
  console.error('Run npm run docs:generate and commit the updated documents.');
  process.exitCode = 1;
} else console.log(`${check ? 'Verified' : 'Generated'} ${outputs.size} documents: ${tools.length} MCP tools, ${endpoints.length} API endpoints.`);
